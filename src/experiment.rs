/// PostgreSQL-backed experiment tracking store.
///
/// Mirrors Python's `arc3_agi.experiment.ExperimentStore` — same schema,
/// same lifecycle (claim → running → completed / failed), same
/// `ingest_run` logic that reads `pop_*/fitness_history.json` files and
/// bulk-upserts into `generation_stats`.
use std::path::Path;
use std::{collections::HashMap, fs::File, io::BufReader};

use chrono::Utc;
use ndarray::Array2;
use ndarray_npy::NpzReader;
use postgres::binary_copy::BinaryCopyInWriter;
use postgres::types::Type;
use postgres::{Client, NoTls};
use rand::RngCore;
use serde_json::Value;
use toml::Value as TomlValue;

// Identical to Python's _SCHEMA_SQL (idempotent — safe to run on every start).
const SCHEMA_SQL: &str = "
CREATE TABLE IF NOT EXISTS experiments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT        NOT NULL UNIQUE,
    description  TEXT,
    run_id       TEXT,
    status       TEXT        NOT NULL DEFAULT 'completed'
        CHECK (status IN ('claimed', 'running', 'completed', 'failed')),
    claimed_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at   TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    failed_at    TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    host         TEXT,
    process_id   INTEGER,
    error        TEXT,
    params_json  JSONB       NOT NULL DEFAULT '{}'::jsonb,
    pop_count    INTEGER,
    gen_count    INTEGER
);

ALTER TABLE experiments ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'completed';
ALTER TABLE experiments ADD COLUMN IF NOT EXISTS claimed_at TIMESTAMPTZ NOT NULL DEFAULT now();
ALTER TABLE experiments ADD COLUMN IF NOT EXISTS started_at TIMESTAMPTZ;
ALTER TABLE experiments ADD COLUMN IF NOT EXISTS completed_at TIMESTAMPTZ;
ALTER TABLE experiments ADD COLUMN IF NOT EXISTS failed_at TIMESTAMPTZ;
ALTER TABLE experiments ADD COLUMN IF NOT EXISTS host TEXT;
ALTER TABLE experiments ADD COLUMN IF NOT EXISTS process_id INTEGER;
ALTER TABLE experiments ADD COLUMN IF NOT EXISTS error TEXT;
ALTER TABLE experiments ADD COLUMN IF NOT EXISTS pop_count INTEGER;
ALTER TABLE experiments ADD COLUMN IF NOT EXISTS gen_count INTEGER;
CREATE UNIQUE INDEX IF NOT EXISTS experiments_name_key ON experiments (name);

CREATE TABLE IF NOT EXISTS generation_stats (
    experiment_id BIGINT  NOT NULL,
    pop_id        INTEGER NOT NULL,
    generation    INTEGER NOT NULL,
    min_fitness   REAL    NOT NULL,
    max_fitness   REAL    NOT NULL,
    mean_fitness  REAL    NOT NULL,
    duration_s    REAL    NOT NULL,
    PRIMARY KEY (experiment_id, pop_id, generation),
    FOREIGN KEY (experiment_id) REFERENCES experiments(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS checkpoint_diagnostics (
    experiment_id                   BIGINT  NOT NULL,
    pop_id                          INTEGER NOT NULL,
    generation                      INTEGER NOT NULL,
    num_automata                    INTEGER NOT NULL,
    state_bits                      INTEGER NOT NULL,
    input_bits                      INTEGER NOT NULL,
    output_bits                     INTEGER NOT NULL,
    num_clauses                     INTEGER NOT NULL,
    clause_density_mean             REAL    NOT NULL,
    clause_density_std              REAL    NOT NULL,
    zero_literal_clause_rate        REAL    NOT NULL,
    polarity_abs_mean               REAL    NOT NULL,
    state_row_density_mean          REAL    NOT NULL,
    response_row_density_mean       REAL    NOT NULL,
    state_response_density_gap      REAL    NOT NULL,
    literal_state_entropy_mean      REAL    NOT NULL,
    literal_state_entropy_std       REAL    NOT NULL,
    clause_churn_rate               REAL,
    PRIMARY KEY (experiment_id, pop_id, generation),
    FOREIGN KEY (experiment_id) REFERENCES experiments(id) ON DELETE CASCADE
);
";

const LOG2_3: f64 = 1.584962500721156;

#[derive(Clone)]
struct CheckpointMasks {
    pos: Vec<u64>,
    neg: Vec<u64>,
    input_bits: usize,
}

#[derive(Clone)]
struct CheckpointDiagnosticRow {
    experiment_id: i64,
    pop_id: i32,
    generation: i32,
    num_automata: i32,
    state_bits: i32,
    input_bits: i32,
    output_bits: i32,
    num_clauses: i32,
    clause_density_mean: f32,
    clause_density_std: f32,
    zero_literal_clause_rate: f32,
    polarity_abs_mean: f32,
    state_row_density_mean: f32,
    response_row_density_mean: f32,
    state_response_density_gap: f32,
    literal_state_entropy_mean: f32,
    literal_state_entropy_std: f32,
    clause_churn_rate: Option<f32>,
}

const DEFAULT_DATABASE_URL: &str = "postgresql://arc3_agi:arc3_agi@localhost:5432/arc3_agi";

pub fn resolve_database_url(explicit: Option<&str>) -> String {
    if let Some(url) = explicit {
        return url.to_string();
    }
    if let Ok(url) = std::env::var("DATABASE_URL") {
        return url;
    }
    DEFAULT_DATABASE_URL.to_string()
}

pub fn generate_run_id() -> String {
    let timestamp = Utc::now().format("%Y%m%dT%H%M%S");
    let suffix = rand::rng().next_u32() & 0x00ff_ffff;
    format!("{timestamp}_{suffix:06x}")
}

#[allow(clippy::too_many_arguments)]
pub fn run_tracked_experiment<Run>(
    name: &str,
    description: &str,
    params: &Value,
    base_dir: &Path,
    database_url: Option<&str>,
    run: Run,
) -> Result<(), Box<dyn std::error::Error>>
where
    Run: FnOnce(&str, &Path) -> Result<(), Box<dyn std::error::Error>>,
{
    let database_url = resolve_database_url(database_url);
    let run_id = generate_run_id();
    let run_dir = base_dir.join(&run_id);
    let mut store = ExperimentStore::connect(&database_url)?;
    let (experiment_id, already_completed) =
        store.claim_experiment(name, description, &run_id, params)?;
    if already_completed {
        println!("\nExperiment '{name}' already completed -> id={experiment_id}; skipping.");
        return Ok(());
    }

    store.mark_running(experiment_id)?;
    let interrupt_database_url = database_url.clone();
    ctrlc::set_handler(move || {
        eprintln!("\nCtrl-C received; marking experiment {experiment_id} as failed.");
        match ExperimentStore::connect(&interrupt_database_url) {
            Ok(mut interrupt_store) => {
                if let Err(error) =
                    interrupt_store.mark_failed(experiment_id, "interrupted by Ctrl-C")
                {
                    eprintln!("Failed to update experiment {experiment_id}: {error}");
                }
            }
            Err(error) => eprintln!("Failed to connect to the experiment database: {error}"),
        }
        std::process::exit(130);
    })?;
    drop(store);

    let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| run(&run_id, &run_dir)));
    match result {
        Ok(Ok(())) => {
            let mut store = ExperimentStore::connect(&database_url)?;
            let rows = store.ingest_run(experiment_id, &run_dir)?;
            let diagnostics_rows = store.ingest_checkpoint_diagnostics(experiment_id, &run_dir)?;
            store.mark_completed(experiment_id)?;
            println!(
                "\nExperiment '{name}' done -> id={experiment_id}  ({rows} generation-stat rows, {diagnostics_rows} checkpoint diagnostics)"
            );
            Ok(())
        }
        Ok(Err(error)) => {
            let message = error.to_string();
            let mut store = ExperimentStore::connect(&database_url)?;
            store.mark_failed(experiment_id, &message)?;
            Err(error)
        }
        Err(payload) => {
            let message = if let Some(message) = payload.downcast_ref::<String>() {
                message.clone()
            } else if let Some(message) = payload.downcast_ref::<&str>() {
                message.to_string()
            } else {
                "unknown panic".into()
            };
            let mut store = ExperimentStore::connect(&database_url)?;
            store.mark_failed(experiment_id, &message)?;
            Err(format!("pool panicked: {message}").into())
        }
    }
}

