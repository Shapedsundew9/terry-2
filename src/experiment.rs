/// PostgreSQL-backed experiment tracking store.
///
/// Mirrors Python's `arc3_agi.experiment.ExperimentStore` — same schema,
/// same lifecycle (claim → running → completed / failed), same
/// `ingest_run` logic that reads `pop_*/fitness_history.json` files and
/// bulk-upserts into `generation_stats`.
use std::path::Path;

use chrono::Utc;
use postgres::binary_copy::BinaryCopyInWriter;
use postgres::types::Type;
use postgres::{Client, NoTls};
use rand::RngCore;
use serde_json::Value;

// Identical to Python's _SCHEMA_SQL (idempotent — safe to run on every start).
const SCHEMA_SQL: &str = "
CREATE TABLE IF NOT EXISTS experiments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT        NOT NULL UNIQUE,
    description  TEXT,
    run_id       TEXT,
    status       TEXT        NOT NULL DEFAULT 'completed'
        CHECK (status IN ('claimed', 'running', 'completed', 'failed')),
    claimed_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at   TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    failed_at    TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    host         TEXT,
    process_id   INTEGER,
    error        TEXT,
    params_json  JSONB       NOT NULL DEFAULT '{}'::jsonb,
    pop_count    INTEGER,
    gen_count    INTEGER
);

ALTER TABLE experiments ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'completed';
ALTER TABLE experiments ADD COLUMN IF NOT EXISTS claimed_at TIMESTAMPTZ NOT NULL DEFAULT now();
ALTER TABLE experiments ADD COLUMN IF NOT EXISTS started_at TIMESTAMPTZ;
ALTER TABLE experiments ADD COLUMN IF NOT EXISTS completed_at TIMESTAMPTZ;
ALTER TABLE experiments ADD COLUMN IF NOT EXISTS failed_at TIMESTAMPTZ;
ALTER TABLE experiments ADD COLUMN IF NOT EXISTS host TEXT;
ALTER TABLE experiments ADD COLUMN IF NOT EXISTS process_id INTEGER;
ALTER TABLE experiments ADD COLUMN IF NOT EXISTS error TEXT;
ALTER TABLE experiments ADD COLUMN IF NOT EXISTS pop_count INTEGER;
ALTER TABLE experiments ADD COLUMN IF NOT EXISTS gen_count INTEGER;
CREATE UNIQUE INDEX IF NOT EXISTS experiments_name_key ON experiments (name);

CREATE TABLE IF NOT EXISTS generation_stats (
    experiment_id BIGINT  NOT NULL,
    pop_id        INTEGER NOT NULL,
    generation    INTEGER NOT NULL,
    min_fitness   REAL    NOT NULL,
    max_fitness   REAL    NOT NULL,
    mean_fitness  REAL    NOT NULL,
    duration_s    REAL    NOT NULL,
    PRIMARY KEY (experiment_id, pop_id, generation),
    FOREIGN KEY (experiment_id) REFERENCES experiments(id) ON DELETE CASCADE
);
";

const DEFAULT_DATABASE_URL: &str = "postgresql://arc3_agi:arc3_agi@localhost:5432/arc3_agi";

pub fn resolve_database_url(explicit: Option<&str>) -> String {
    if let Some(url) = explicit {
        return url.to_string();
    }
    if let Ok(url) = std::env::var("DATABASE_URL") {
        return url;
    }
    DEFAULT_DATABASE_URL.to_string()
}

pub fn generate_run_id() -> String {
    let timestamp = Utc::now().format("%Y%m%dT%H%M%S");
    let suffix = rand::rng().next_u32() & 0x00ff_ffff;
    format!("{timestamp}_{suffix:06x}")
}

#[allow(clippy::too_many_arguments)]
pub fn run_tracked_experiment<Run>(
    name: &str,
    description: &str,
    params: &Value,
    base_dir: &Path,
    database_url: Option<&str>,
    run: Run,
) -> Result<(), Box<dyn std::error::Error>>
where
    Run: FnOnce(&str, &Path) -> Result<(), Box<dyn std::error::Error>>,
{
    let database_url = resolve_database_url(database_url);
    let run_id = generate_run_id();
    let run_dir = base_dir.join(&run_id);
    let mut store = ExperimentStore::connect(&database_url)?;
    let (experiment_id, already_completed) =
        store.claim_experiment(name, description, &run_id, params)?;
    if already_completed {
        println!("\nExperiment '{name}' already completed -> id={experiment_id}; skipping.");
        return Ok(());
    }

    store.mark_running(experiment_id)?;
    let interrupt_database_url = database_url.clone();
    ctrlc::set_handler(move || {
        eprintln!("\nCtrl-C received; marking experiment {experiment_id} as failed.");
        match ExperimentStore::connect(&interrupt_database_url) {
            Ok(mut interrupt_store) => {
                if let Err(error) =
                    interrupt_store.mark_failed(experiment_id, "interrupted by Ctrl-C")
                {
                    eprintln!("Failed to update experiment {experiment_id}: {error}");
                }
            }
            Err(error) => eprintln!("Failed to connect to the experiment database: {error}"),
        }
        std::process::exit(130);
    })?;
    drop(store);

    let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| run(&run_id, &run_dir)));
    match result {
        Ok(Ok(())) => {
            let mut store = ExperimentStore::connect(&database_url)?;
            let rows = store.ingest_run(experiment_id, &run_dir)?;
            store.mark_completed(experiment_id)?;
            println!(
                "\nExperiment '{name}' done -> id={experiment_id}  ({rows} generation-stat rows)"
            );
            Ok(())
        }
        Ok(Err(error)) => {
            let message = error.to_string();
            let mut store = ExperimentStore::connect(&database_url)?;
            store.mark_failed(experiment_id, &message)?;
            Err(error)
        }
        Err(payload) => {
            let message = if let Some(message) = payload.downcast_ref::<String>() {
                message.clone()
            } else if let Some(message) = payload.downcast_ref::<&str>() {
                message.to_string()
            } else {
                "unknown panic".into()
            };
            let mut store = ExperimentStore::connect(&database_url)?;
            store.mark_failed(experiment_id, &message)?;
            Err(format!("pool panicked: {message}").into())
        }
    }
}

// ---------------------------------------------------------------------------
// ExperimentStore
// ---------------------------------------------------------------------------

pub struct ExperimentStore {
    client: Client,
}

impl ExperimentStore {
    pub fn connect(database_url: &str) -> Result<Self, postgres::Error> {
        let mut client = Client::connect(database_url, NoTls)?;
        client.batch_execute(SCHEMA_SQL)?;
        Ok(ExperimentStore { client })
    }

    /// Claim an experiment name atomically.
    ///
    /// Returns `(experiment_id, already_completed)`.
    /// - `already_completed = true` → run is skipped, use existing id.
    /// - Failed experiments are reset and reclaimed in place.
    /// - Raises an error if the name is claimed/running by another process.
    pub fn claim_experiment(
        &mut self,
        name: &str,
        description: &str,
        run_id: &str,
        params_json: &Value,
    ) -> Result<(i64, bool), Box<dyn std::error::Error>> {
        let host = hostname::get()
            .map(|h| h.to_string_lossy().into_owned())
            .unwrap_or_else(|_| "unknown".into());
        let pid = std::process::id() as i32;

        let mut transaction = self.client.transaction()?;
        let row = transaction.query_opt(
            "INSERT INTO experiments (name, description, run_id, status, host, process_id, params_json)
             VALUES ($1, $2, $3, 'claimed', $4, $5, $6)
             ON CONFLICT (name) DO UPDATE SET
                description = EXCLUDED.description,
                run_id = EXCLUDED.run_id,
                status = 'claimed',
                claimed_at = EXCLUDED.claimed_at,
                started_at = NULL,
                completed_at = NULL,
                failed_at = NULL,
                created_at = EXCLUDED.created_at,
                host = EXCLUDED.host,
                process_id = EXCLUDED.process_id,
                error = NULL,
                params_json = EXCLUDED.params_json,
                pop_count = 0,
                gen_count = 0
             WHERE experiments.status = 'failed'
             RETURNING id",
            &[&name, &description, &run_id, &host, &pid, params_json],
        )?;

        if let Some(row) = row {
            let id: i64 = row.get(0);
            transaction.execute(
                "DELETE FROM generation_stats WHERE experiment_id = $1",
                &[&id],
            )?;
            transaction.commit()?;
            return Ok((id, false));
        }

        // Conflict — check existing status.
        let existing = transaction.query_one(
            "SELECT id, status FROM experiments WHERE name = $1",
            &[&name],
        )?;
        let id: i64 = existing.get(0);
        let status: String = existing.get(1);
        transaction.commit()?;

        if status == "completed" {
            return Ok((id, true));
        }

        Err(format!(
            "Experiment '{name}' already exists with status '{status}' — \
             cannot claim"
        )
        .into())
    }

    pub fn mark_running(&mut self, experiment_id: i64) -> Result<(), postgres::Error> {
        self.client.execute(
            "UPDATE experiments
             SET status = 'running',
                 started_at = COALESCE(started_at, now()),
                 error = NULL
             WHERE id = $1",
            &[&experiment_id],
        )?;
        Ok(())
    }

    pub fn mark_completed(&mut self, experiment_id: i64) -> Result<(), postgres::Error> {
        self.client.execute(
            "UPDATE experiments
             SET status = 'completed',
                 completed_at = now(),
                 failed_at = NULL,
                 error = NULL
             WHERE id = $1",
            &[&experiment_id],
        )?;
        Ok(())
    }

    pub fn mark_failed(&mut self, experiment_id: i64, error: &str) -> Result<(), postgres::Error> {
        self.client.execute(
            "UPDATE experiments
             SET status = 'failed',
                 failed_at = now(),
                 error = $2
             WHERE id = $1
               AND status IN ('claimed', 'running')",
            &[&experiment_id, &error],
        )?;
        Ok(())
    }

    /// Read all `pop_*/fitness_history.json` files under `run_dir` and
    /// upsert their records into `generation_stats`.
    ///
    /// Returns the number of rows upserted.
    pub fn ingest_run(
        &mut self,
        experiment_id: i64,
        run_dir: &Path,
    ) -> Result<usize, Box<dyn std::error::Error>> {
        let mut rows = Vec::new();

        // Collect pop_*/fitness_history.json paths.
        let mut fh_paths: Vec<std::path::PathBuf> = std::fs::read_dir(run_dir)?
            .filter_map(|e| e.ok())
            .filter(|e| e.file_name().to_string_lossy().starts_with("pop_"))
            .map(|e| e.path().join("fitness_history.json"))
            .filter(|p| p.exists())
            .collect();
        fh_paths.sort();

        for entry in fh_paths {
            let json_str = std::fs::read_to_string(&entry)?;
            let doc: Value = serde_json::from_str(&json_str)?;

            let pop_id = doc["pop_id"].as_i64().unwrap_or(0) as i32;
            let history = doc["history"].as_array().ok_or("missing history array")?;

            for record in history {
                let generation = record["generation"].as_i64().unwrap_or(0) as i32;
                let min_f = record["min_fitness"].as_f64().unwrap_or(0.0) as f32;
                let max_f = record["max_fitness"].as_f64().unwrap_or(0.0) as f32;
                let mean_f = record["mean_fitness"].as_f64().unwrap_or(0.0) as f32;
                let dur = record["duration_s"].as_f64().unwrap_or(0.0) as f32;

                rows.push((experiment_id, pop_id, generation, min_f, max_f, mean_f, dur));
            }
        }

        let total = rows.len();
        let mut transaction = self.client.transaction()?;
        if !rows.is_empty() {
            transaction.batch_execute(
                "CREATE TEMP TABLE ingest_generation_stats
                    (LIKE generation_stats INCLUDING DEFAULTS)
                 ON COMMIT DROP",
            )?;

            let copy_sink = transaction.copy_in(
                "COPY ingest_generation_stats
                    (experiment_id, pop_id, generation,
                     min_fitness, max_fitness, mean_fitness, duration_s)
                 FROM STDIN BINARY",
            )?;
            let mut copy_writer = BinaryCopyInWriter::new(
                copy_sink,
                &[
                    Type::INT8,
                    Type::INT4,
                    Type::INT4,
                    Type::FLOAT4,
                    Type::FLOAT4,
                    Type::FLOAT4,
                    Type::FLOAT4,
                ],
            );
            for (experiment_id, pop_id, generation, min_f, max_f, mean_f, dur) in &rows {
                copy_writer.write(&[
                    experiment_id,
                    pop_id,
                    generation,
                    min_f,
                    max_f,
                    mean_f,
                    dur,
                ])?;
            }
            copy_writer.finish()?;

            transaction.execute(
                "INSERT INTO generation_stats
                    (experiment_id, pop_id, generation,
                     min_fitness, max_fitness, mean_fitness, duration_s)
                 SELECT experiment_id, pop_id, generation,
                        min_fitness, max_fitness, mean_fitness, duration_s
                 FROM ingest_generation_stats
                 ON CONFLICT (experiment_id, pop_id, generation)
                 DO UPDATE SET
                    min_fitness  = EXCLUDED.min_fitness,
                    max_fitness  = EXCLUDED.max_fitness,
                    mean_fitness = EXCLUDED.mean_fitness,
                    duration_s   = EXCLUDED.duration_s",
                &[],
            )?;
        }

        transaction.execute(
            "UPDATE experiments
             SET pop_count = (
                     SELECT COUNT(DISTINCT pop_id)
                     FROM generation_stats
                     WHERE experiment_id = $1
                 ),
                 gen_count = (
                     SELECT MAX(generation)
                     FROM generation_stats
                     WHERE experiment_id = $1
                 )
             WHERE id = $1",
            &[&experiment_id],
        )?;
        transaction.commit()?;

        Ok(total)
    }
}

#[cfg(test)]
mod tests {
    use std::time::{SystemTime, UNIX_EPOCH};

    use serde_json::json;

    use super::*;

    fn test_database_url() -> Option<String> {
        std::env::var("TEST_DATABASE_URL")
            .or_else(|_| std::env::var("DATABASE_URL"))
            .ok()
    }

    #[test]
    fn failed_experiment_is_reclaimed_and_cleared() -> Result<(), Box<dyn std::error::Error>> {
        let Some(database_url) = test_database_url() else {
            return Ok(());
        };
        let suffix = SystemTime::now().duration_since(UNIX_EPOCH)?.as_nanos();
        let name = format!("rust-failed-{}-{suffix}", std::process::id());
        let mut store = ExperimentStore::connect(&database_url)?;
        let (experiment_id, already_completed) =
            store.claim_experiment(&name, "old description", "old-run", &json!({"seed": 1}))?;
        assert!(!already_completed);

        store.client.execute(
            "INSERT INTO generation_stats
                (experiment_id, pop_id, generation, min_fitness, max_fitness, mean_fitness, duration_s)
             VALUES ($1, 0, 1, 0.1, 0.8, 0.4, 1.2)",
            &[&experiment_id],
        )?;
        store.mark_failed(experiment_id, "interrupted")?;

        let (retried_id, retried_completed) =
            store.claim_experiment(&name, "new description", "new-run", &json!({"seed": 2}))?;
        let row = store.client.query_one(
            "SELECT description, run_id, status, params_json, pop_count, gen_count,
                    (SELECT COUNT(*) FROM generation_stats WHERE experiment_id = $1)
             FROM experiments
             WHERE id = $1",
            &[&experiment_id],
        )?;
        store.mark_completed(experiment_id)?;
        store.mark_failed(experiment_id, "late interrupt")?;
        let final_status: String = store
            .client
            .query_one(
                "SELECT status FROM experiments WHERE id = $1",
                &[&experiment_id],
            )?
            .get(0);
        store
            .client
            .execute("DELETE FROM experiments WHERE id = $1", &[&experiment_id])?;

        assert_eq!(retried_id, experiment_id);
        assert!(!retried_completed);
        assert_eq!(row.get::<_, String>(0), "new description");
        assert_eq!(row.get::<_, String>(1), "new-run");
        assert_eq!(row.get::<_, String>(2), "claimed");
        assert_eq!(row.get::<_, Value>(3), json!({"seed": 2}));
        assert_eq!(row.get::<_, i32>(4), 0);
        assert_eq!(row.get::<_, i32>(5), 0);
        assert_eq!(row.get::<_, i64>(6), 0);
        assert_eq!(final_status, "completed");
        Ok(())
    }

    #[test]
    fn ingest_run_bulk_upserts_generation_stats() -> Result<(), Box<dyn std::error::Error>> {
        let Some(database_url) = test_database_url() else {
            return Ok(());
        };
        let suffix = SystemTime::now().duration_since(UNIX_EPOCH)?.as_nanos();
        let name = format!("rust-ingest-{}-{suffix}", std::process::id());
        let run_dir = std::env::temp_dir().join(&name);
        std::fs::create_dir_all(run_dir.join("pop_0"))?;
        std::fs::create_dir_all(run_dir.join("pop_1"))?;
        std::fs::write(
            run_dir.join("pop_0/fitness_history.json"),
            json!({
                "pop_id": 0,
                "history": [
                    {"generation": 1, "min_fitness": 0.1, "max_fitness": 0.8,
                     "mean_fitness": 0.4, "duration_s": 1.2},
                    {"generation": 2, "min_fitness": 0.2, "max_fitness": 0.9,
                     "mean_fitness": 0.5, "duration_s": 1.1}
                ]
            })
            .to_string(),
        )?;
        std::fs::write(
            run_dir.join("pop_1/fitness_history.json"),
            json!({
                "pop_id": 1,
                "history": [
                    {"generation": 1, "min_fitness": 0.3, "max_fitness": 0.7,
                     "mean_fitness": 0.5, "duration_s": 1.0}
                ]
            })
            .to_string(),
        )?;

        let mut store = ExperimentStore::connect(&database_url)?;
        let (experiment_id, _) =
            store.claim_experiment(&name, "bulk ingest", "test-run", &json!({}))?;
        assert_eq!(store.ingest_run(experiment_id, &run_dir)?, 3);

        std::fs::write(
            run_dir.join("pop_1/fitness_history.json"),
            json!({
                "pop_id": 1,
                "history": [
                    {"generation": 1, "min_fitness": 0.4, "max_fitness": 1.0,
                     "mean_fitness": 0.6, "duration_s": 0.9}
                ]
            })
            .to_string(),
        )?;
        assert_eq!(store.ingest_run(experiment_id, &run_dir)?, 3);

        let row = store.client.query_one(
            "SELECT pop_count, gen_count,
                    (SELECT COUNT(*) FROM generation_stats WHERE experiment_id = $1),
                    (SELECT max_fitness FROM generation_stats
                     WHERE experiment_id = $1 AND pop_id = 1 AND generation = 1)
             FROM experiments WHERE id = $1",
            &[&experiment_id],
        )?;
        store
            .client
            .execute("DELETE FROM experiments WHERE id = $1", &[&experiment_id])?;
        std::fs::remove_dir_all(run_dir)?;

        assert_eq!(row.get::<_, i32>(0), 2);
        assert_eq!(row.get::<_, i32>(1), 2);
        assert_eq!(row.get::<_, i64>(2), 3);
        assert_eq!(row.get::<_, f32>(3), 1.0);
        Ok(())
    }
}
